def normalize_subject(raw: str):
    import re
    s = raw.strip().lower().replace(".", "").replace(",", "").replace(" ", "").strip()
    # 1. Точное совпадение
    if s in SUBJECT_SYNONYMS:
        return SUBJECT_SYNONYMS[s]
    # 2. Подстрока — выбрать наиболее длинное совпадение
    best = None
    best_len = 0
    for key, val in SUBJECT_SYNONYMS.items():
        if s in key or key in s:
            if len(key) > best_len:
                best_len = len(key)
                best = val
    if best:
        return best
    # 3. Fallback: создать id из raw
    slug = re.sub(r'[^a-zа-я0-9]+', '_', s)[:20].strip('_')
    if not slug:
        slug = "unknown"
    weight = 5
    if "математ" in s or "алгебра" in s or "геометрия" in s or "физика" in s or "химия" in s:
        weight = 9
    elif "язык" in s:
        weight = 7
    return (slug, raw.strip().title()[:30], weight, None)
